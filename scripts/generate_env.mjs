import { execSync } from "node:child_process";
import path from "node:path";

import * as utils from "./utils.mjs";

const __dirname = import.meta.dirname;

async function main() {
  const pnpmPath = process.platform === "win32"
    ? execSync("where pnpm").toString().split("\n")[0].trim()
    : execSync("which pnpm").toString().trim();
  if (utils.str.isEmpty(pnpmPath)) {
    console.error("No pnpm in PATH found.");
    return;
  }

  const dockerPath = process.platform === "win32"
    ? execSync("where docker").toString().split("\n")[0].trim()
    : execSync("which docker").toString().trim();
  if (utils.str.isEmpty(dockerPath)) {
    console.error("No docker in PATH found.");
    return;
  }

  // Resend API Key
  const resend = await utils.env.ask("Your Resend API Key", "resend.api.key");
  if (!resend) {
    throw new Error("Resend API Key is required.");
  }

  const resendFromAddress = await utils.env.ask(
    "Your Resend From Address (Example: oasis-app <no-reply@oasis-app.dev>)",
    "resend.from.address",
  );
  if (!resendFromAddress) {
    throw new Error("Resend From Address is required.");
  }

  // Sentry token
  const sentry = await utils.env.ask("Your Sentry Auth Token", "sentry.auth.token");
  if (!sentry) {
    throw new Error("Sentry Auth Token is required.");
  }

  const orgName = await utils.env.ask("Your Organization Name", "next.public.project.org.name");
  if (!orgName) {
    throw new Error("Organization Name is required.");
  }

  const orgLogo = await utils.env.ask("Your Organization Logo Path", "next.public.project.org.seal");
  if (!orgLogo) {
    throw new Error("Organization Logo is required.");
  }

  // Token generation for authentication
  const token = utils.token.generatePassword(32, "!#%&()*+,/:;<=>?@[]^`{|}");
  utils.env.write("better.auth.secret", token);
  utils.env.write("better.auth.url", "http://localhost:3000");

  // Database configuration
  const dbPassword = utils.token.generatePassword(32);
  utils.env.write("postgres.password", dbPassword);

  const dbUser = await utils.env.ask("Your Database username", "postgres.username", "postgres");
  const dbName = await utils.env.ask("Your Database name", "postgres.db", "oasis");
  const dbHost = await utils.env.ask("Your Database host", "postgres.host", "localhost");

  let dbPort = await utils.env.ask(
    "Your PostgreSQL port (leave blank for autogenerated port)",
    "postgres.port",
  );
  if (utils.str.isEmpty(dbPort)) {
    dbPort = Math.floor(Math.random() * (65535 - 1024 + 1) + 1024).toString();
    utils.env.write("postgres.port", dbPort);
  }

  // Redis configuration
  const redisHost = await utils.env.ask("Redis Host", "redis.host", "localhost");
  let redisPort = await utils.env.ask("Redis Port (leave blank for autogenerated port)", "redis.port");
  if (utils.str.isEmpty(redisPort)) {
    redisPort = Math.floor(Math.random() * (65535 - 1024 + 1) + 1024).toString();
    utils.env.write("redis.port", redisPort);
  }

  utils.env.write("redis.url", utils.db.createRedisConnectionString(redisHost, redisPort));

  // Generate a connection string
  const connectionString = utils.db.createConnectionString({
    username: dbUser,
    password: dbPassword,
    name: dbName,
    host: dbHost,
    port: dbPort,
  });
  utils.env.write("database.url", connectionString);

  // Write to root
  await utils.env.export(path.join(__dirname, "../.env"));

  // Run the docker-compose
  await utils.process.spawnAsync(dockerPath, ["compose", "up", "-d", "--wait"], {
    cwd: path.join(__dirname, "../"),
  });

  // Wait 10s...
  await utils.timers.wait(5);

  try {
    // Create the database in preparation of pushing the schema to a database
    console.log("Creating database...");
    await utils.db.setupDatabase({
      username: dbUser,
      password: dbPassword,
      name: dbName,
      host: dbHost,
      port: dbPort,
    });

    // Wait 5s...
    await utils.timers.wait(5);

    // Start the schema migration
    console.log("Running migrations...");
    await utils.process.spawnAsync(pnpmPath, ["run", "db:migrate"], {
      cwd: path.join(__dirname, "../"),
      shell: true,
    });

    await utils.timers.wait(5);

    // Seed
    console.log("Running seed...");
    await utils.process.spawnAsync(pnpmPath, ["run", "db:seed"], {
      cwd: path.join(__dirname, "../"),
      shell: true,
    });

    console.log("");
    console.log("Your development environment has finished configuring.");
    console.log("");
    console.log("Before you can do anything, you need to do this first:");
    console.log("  1. Run the server: pnpm dev");
    console.log("  2. Create and login the enroller account: pnpm run enroller -- --enable");
    console.log("     This will generate a account solely for setting up offices, roles, permissions and inviting users to the org.");
    console.log("     After the setup, you can disable the account by running pnpm run enroller -- --disable");
    console.log("     To re-enable the enroller account, run pnpm run enroller -- --enable");
    console.log("  3. Then seed the rest of the data: pnpm run db:seed");
    console.log("");
    console.log("Happy coding!");
    console.log("");
  } catch (e) {
    console.error("");
    console.error("One or more commands failed to run to setup your database. Use the exception below for troubleshooting:");
    console.error("");
    console.error("============================================================");
    console.error(e);
    console.error("============================================================");
    console.error("");
    console.error("To restart the env setup again, run:");
    console.error("  1. docker compose down");
    console.error("  2. pnpm run setup");
    console.error("");
  }
}

main().catch(console.error);
